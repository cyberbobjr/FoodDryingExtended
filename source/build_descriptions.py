def build(d):
    with open(os.path.join(TRANSLATE, d["lang"], "Recipes.json"), encoding="utf-8") as fh:
        names = json.load(fh)
    out = ["[h1]Food Drying Extended[/h1]", "", f"[b]Build 42.21 · {d['players']}[/b]", "", d["intro"], "",
           f"[h2]{d['h_more']}[/h2]", "[list]"]
    out += [f"[*]{m}" for m in d["more"]]
    out += ["[/list]", "", f"[h2]{d['h_recipes']}[/h2]", "[table]",
            "[tr]" + "".join(f"[th]{h}[/th]" for h in d["th"]) + "[/tr]"]
    rows = [d["slice_row"][0]] + d["rows"]
    results = [d["slice_row"][1]] + d["res"]
    for key, ingredients, result in zip(ROWS, rows, results):
        out.append(f"[tr][td][b]{names[key]}[/b][/td][td]{ingredients}[/td][td]{result}[/td][/tr]")
    out += ["[/table]", "", f"[h2]{d['h_notes']}[/h2]", "[list]"]
    out += [f"[*]{n}" for n in d["notes"]]
    out += ["[/list]", "", "[h2]Discord[/h2]", "", d["discord"], DISCORD, "", f"[h2]{d['h_credits']}[/h2]"]
    out += d["credits"]
    return "\n".join(out) + "\n"


def main():
    for suffix, d in L.items():
        assert len(d["rows"]) + 1 == len(ROWS) == len(d["res"]) + 1, suffix
        text = build(d)
        size = len(text.encode("utf-8"))
        assert size < 7800, (suffix, size)
        name = "README.steam" + ("." + suffix if suffix else "")
        with open(os.path.join(PROJECT, name), "w", encoding="utf-8", newline="\n") as fh:
            fh.write(text)
        print(f"{name}: {size} bytes")
    # workshop.txt keeps the English description in sync
    path = os.path.join(PROJECT, "workshop.txt")
    with open(path, encoding="utf-8") as fh:
        lines = fh.read().split("\n")
    head = [l for l in lines if l.startswith(("version=", "id=", "title="))]
    tail = [l for l in lines if l.startswith(("tags=", "visibility="))]
    desc = ["description=" + l for l in build(L[""]).rstrip("\n").split("\n")]
    with open(path, "w", encoding="utf-8", newline="\n") as fh:
        fh.write("\n".join(head + desc + tail) + "\n")


main()
